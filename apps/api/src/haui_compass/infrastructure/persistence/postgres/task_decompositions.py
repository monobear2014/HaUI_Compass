"""PostgreSQL candidate sessions for task decomposition.

Serverless instances do not share memory, so a candidate generated by one request must be readable
by the confirming request. Sessions are stored as an explicit JSON snapshot; only confirmed tasks
ever reach the task repository, exactly as with the in-memory store.
"""

from collections.abc import Callable
from datetime import UTC, datetime, timedelta
from typing import Any, cast
from uuid import UUID

from sqlalchemy.orm import Session

from haui_compass.application.lms_mapping import student_id_for
from haui_compass.application.ports.lms import ExternalRef
from haui_compass.application.ports.task_decomposition import (
    CandidateSource,
    ConfirmedCandidateEdit,
    ConfirmedTaskDecomposition,
    FallbackReason,
    TaskCandidate,
    TaskCandidateId,
    TaskDecompositionSession,
    TaskDecompositionSessionId,
)
from haui_compass.application.ports.tasks import StoredTask
from haui_compass.application.ports.transactions import PersistenceTransactionManager
from haui_compass.application.use_cases.task_decomposition import (
    TaskDecompositionError,
    TaskDecompositionErrorCode,
)
from haui_compass.domain.assignments.assignment import AssignmentId
from haui_compass.domain.students.ids import StudentId
from haui_compass.domain.tasks.task import Task, TaskId, TaskStatus
from haui_compass.infrastructure.persistence.postgres.models import TaskDecompositionSessionRow


class PostgresTaskDecompositionSessionStore:
    def __init__(
        self,
        session_provider: Callable[[], Session],
        transaction_manager: PersistenceTransactionManager,
    ) -> None:
        self._session_provider = session_provider
        self._tx = transaction_manager

    def save(self, session: TaskDecompositionSession) -> TaskDecompositionSession:
        def operation() -> TaskDecompositionSession:
            db = self._session_provider()
            row = db.get(TaskDecompositionSessionRow, session.id)
            if row is not None:
                if _decode_session(row) != session:
                    raise TaskDecompositionError(
                        TaskDecompositionErrorCode.SESSION_CONFLICT,
                        "task decomposition session id already exists",
                    )
                return session
            db.add(
                TaskDecompositionSessionRow(
                    session_id=session.id,
                    student_id=student_id_for(session.student),
                    session=_session_json(session),
                    confirmation=None,
                    created_at=datetime.now(UTC),
                )
            )
            db.flush()
            return session

        return self._tx.run(operation)

    def get(self, session_id: TaskDecompositionSessionId) -> TaskDecompositionSession | None:
        def operation() -> TaskDecompositionSession | None:
            row = self._session_provider().get(TaskDecompositionSessionRow, session_id)
            return None if row is None else _decode_session(row)

        return self._tx.run(operation)

    def confirmation(
        self, session_id: TaskDecompositionSessionId
    ) -> ConfirmedTaskDecomposition | None:
        def operation() -> ConfirmedTaskDecomposition | None:
            row = self._session_provider().get(TaskDecompositionSessionRow, session_id)
            if row is None or row.confirmation is None:
                return None
            return _confirmation(session_id, row.confirmation)

        return self._tx.run(operation)

    def save_confirmation(
        self, confirmation: ConfirmedTaskDecomposition
    ) -> ConfirmedTaskDecomposition:
        def operation() -> ConfirmedTaskDecomposition:
            row = self._session_provider().get(
                TaskDecompositionSessionRow, confirmation.session_id, with_for_update=True
            )
            if row is None:
                raise TaskDecompositionError(
                    TaskDecompositionErrorCode.SESSION_NOT_FOUND,
                    "task decomposition session was not found",
                )
            if row.confirmation is not None:
                if _confirmation(confirmation.session_id, row.confirmation) != confirmation:
                    raise TaskDecompositionError(
                        TaskDecompositionErrorCode.SESSION_CONFLICT,
                        "task decomposition confirmation conflicts with an existing confirmation",
                    )
                return confirmation
            row.confirmation = _confirmation_json(confirmation)
            self._session_provider().flush()
            return confirmation

        return self._tx.run(operation)


def _ref(value: ExternalRef) -> dict[str, str]:
    return {"provider": value.provider, "id": value.id}


def _from_ref(value: Any) -> ExternalRef:
    return ExternalRef(str(value["provider"]), str(value["id"]))


def _session_json(session: TaskDecompositionSession) -> dict[str, object]:
    return {
        "student": _ref(session.student),
        "assignment": _ref(session.assignment),
        "assignment_title": session.assignment_title,
        "course_name": session.course_name,
        "source": session.source,
        "fallback_reason": session.fallback_reason,
        "candidates": [
            {
                "id": str(candidate.id),
                "title": candidate.title,
                "estimated_duration_minutes": candidate.estimated_duration_minutes,
                "rationale": candidate.rationale,
                "source": candidate.source,
            }
            for candidate in session.candidates
        ],
    }


def _confirmation_json(confirmation: ConfirmedTaskDecomposition) -> dict[str, object]:
    return {
        "selection": [
            {
                "candidate_id": str(edit.candidate_id),
                "title": edit.title,
                "estimated_duration_minutes": edit.estimated_duration_minutes,
            }
            for edit in confirmation.selection
        ],
        "tasks": [
            {
                "student_id": str(record.student_id),
                "task_id": str(record.task.id),
                "assignment_id": str(record.task.assignment_id),
                "title": record.task.title,
                "estimated_seconds": int(record.task.estimated_duration.total_seconds()),
                "status": record.task.status.value,
                "saved_at": record.saved_at.isoformat(),
            }
            for record in confirmation.tasks
        ],
    }


def _confirmation(
    session_id: TaskDecompositionSessionId, value: dict[str, Any]
) -> ConfirmedTaskDecomposition:
    return ConfirmedTaskDecomposition(
        session_id=session_id,
        selection=tuple(
            ConfirmedCandidateEdit(
                candidate_id=TaskCandidateId(UUID(edit["candidate_id"])),
                title=edit["title"],
                estimated_duration_minutes=int(edit["estimated_duration_minutes"]),
            )
            for edit in value["selection"]
        ),
        tasks=tuple(
            StoredTask(
                student_id=StudentId(UUID(task["student_id"])),
                task=Task(
                    id=TaskId(UUID(task["task_id"])),
                    assignment_id=AssignmentId(UUID(task["assignment_id"])),
                    title=task["title"],
                    estimated_duration=timedelta(seconds=int(task["estimated_seconds"])),
                    status=TaskStatus(task["status"]),
                ),
                saved_at=datetime.fromisoformat(task["saved_at"]),
            )
            for task in value["tasks"]
        ),
    )


def _decode_session(row: TaskDecompositionSessionRow) -> TaskDecompositionSession:
    value = cast(dict[str, Any], row.session)
    return TaskDecompositionSession(
        id=TaskDecompositionSessionId(row.session_id),
        student=_from_ref(value["student"]),
        assignment=_from_ref(value["assignment"]),
        assignment_title=value["assignment_title"],
        course_name=value["course_name"],
        source=cast(CandidateSource, value["source"]),
        fallback_reason=cast(FallbackReason | None, value["fallback_reason"]),
        candidates=tuple(
            TaskCandidate(
                id=TaskCandidateId(UUID(candidate["id"])),
                title=candidate["title"],
                estimated_duration_minutes=int(candidate["estimated_duration_minutes"]),
                rationale=candidate["rationale"],
                source=cast(CandidateSource, candidate["source"]),
            )
            for candidate in value["candidates"]
        ),
    )
